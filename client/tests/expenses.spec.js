import { test, expect } from '@playwright/test'
import { randomUUID } from 'node:crypto'

async function setup(page) {
  await page.goto('/register')
  await page.getByLabel('Nombre completo', { exact: true }).fill('Persona Gastos')
  await page.getByLabel('Correo electrónico', { exact: true }).fill(`${randomUUID()}@example.com`)
  await page.getByLabel('Contraseña', { exact: true }).fill('Una frase ficticia de gastos 123')
  await page.getByLabel('Confirmar contraseña', { exact: true }).fill('Una frase ficticia de gastos 123')
  await page.getByRole('button', { name: 'Crear mi cuenta', exact: true }).click()
  await expect(page).toHaveURL(/\/dashboard$/)
  await page.getByRole('button', { name: /Crear grupo/ }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Nombre del grupo').fill('Viaje de gastos')
  await dialog.getByRole('button', { name: 'Crear grupo', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('link', { name: /Ver grupo Viaje de gastos/ }).click()
  for (const name of ['Ana', 'Pedro', 'Laura']) {
    await page.getByRole('button', { name: /Añadir participante/ }).click()
    await dialog.getByLabel('Nombre del participante').fill(name)
    await dialog.getByRole('button', { name: 'Crear participante', exact: true }).click()
    await expect(dialog).not.toBeVisible()
  }
  await expect(page.getByRole('button', { name: /Añadir gasto/ })).toBeEnabled()
}

async function addExpense(page, amount = '90000') {
  await page.getByRole('button', { name: /Añadir gasto/ }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Descripción del gasto').fill('Cena compartida')
  await dialog.getByLabel('Importe en COP').fill(amount)
  await dialog.getByLabel('Pagó', { exact: true }).selectOption({ label: 'Ana' })
  return dialog
}

test('gasto completo: vista previa, persistencia, edición, balances, bloqueo de miembro y eliminación', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await setup(page)
  const dialog = await addExpense(page)
  await expect(dialog.getByRole('region', { name: 'Vista previa del reparto' }).getByText(/30\.000 COP/)).toHaveCount(3)
  await page.screenshot({ path: 'test-results/expenses-form.png' })
  await dialog.getByRole('button', { name: 'Crear gasto', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('heading', { name: 'Cena compartida', exact: true })).toBeVisible()
  const balances = page.getByRole('table')
  await expect(balances.getByRole('row', { name: /Ana/ })).toContainText('+')
  await expect(balances.getByRole('row', { name: /Ana/ })).toContainText('60.000')
  await expect(page.getByText(/Pedro debe .*30\.000 COP.* a Ana/)).toBeVisible()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: 'test-results/expenses-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: 'test-results/expenses-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Cena compartida', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Eliminar participante Pedro', exact: true }).click()
  await dialog.getByRole('button', { name: 'Eliminar participante', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('asociado a gastos')
  await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await page.getByRole('button', { name: 'Editar gasto Cena compartida', exact: true }).click()
  await dialog.getByLabel('Importe en COP').fill('60000')
  await dialog.getByRole('checkbox', { name: 'Laura', exact: true }).uncheck()
  await dialog.getByRole('button', { name: 'Guardar gasto', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('row', { name: /Ana/ })).toContainText('30.000')
  await expect(page.getByRole('row', { name: /Laura/ })).toContainText('En equilibrio')
  await page.getByRole('button', { name: 'Eliminar gasto Cena compartida', exact: true }).click()
  await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Cena compartida', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Eliminar gasto Cena compartida', exact: true }).click()
  await dialog.getByRole('button', { name: 'Eliminar gasto', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('heading', { name: 'Aún no hay gastos.', exact: true })).toBeVisible()
  await expect(page.getByRole('row', { name: /Ana/ })).toContainText('En equilibrio')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Aún no hay gastos.', exact: true })).toBeVisible()
})

test('importe impar conserva suma y se refleja en métricas reales', async ({ page }) => {
  await setup(page)
  const dialog = await addExpense(page, '101')
  const preview = dialog.getByRole('region', { name: 'Vista previa del reparto' })
  await expect(preview.getByText(/34 COP/)).toHaveCount(2)
  await expect(preview.getByText(/33 COP/)).toHaveCount(1)
  await dialog.getByRole('button', { name: 'Crear gasto', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('heading', { name: 'Cena compartida', exact: true })).toBeVisible()
  await page.getByRole('link', { name: '↗ Dashboard', exact: true }).click()
  const metrics = page.getByRole('region', { name: 'Métricas reales de tus grupos' })
  await expect(metrics).toContainText('101 COP')
  await page.reload()
  await expect(metrics).toContainText('101 COP')
})

test('validación local y errores reales CSRF/422 conservan el formulario', async ({ page }) => {
  await setup(page)
  const dialog = await addExpense(page, '0')
  await dialog.getByRole('button', { name: 'Crear gasto', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('importe entero positivo')
  await dialog.getByLabel('Importe en COP').fill('90000')
  await page.route('**/api/groups/*/expenses', async route => {
    if (route.request().method() === 'POST') {
      await route.continue({ headers: { ...route.request().headers(), 'x-csrf-token': 'incorrecto' } })
    } else await route.continue()
  })
  await dialog.getByRole('button', { name: 'Crear gasto', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('validar esta solicitud')
  await expect(dialog.getByLabel('Descripción del gasto')).toHaveValue('Cena compartida')
  await page.unroute('**/api/groups/*/expenses')
  await page.route('**/api/groups/*/expenses', async route => {
    if (route.request().method() === 'POST') await route.continue({ postData: JSON.stringify({ ...route.request().postDataJSON(), participant_ids: [] }) })
    else await route.continue()
  })
  await dialog.getByRole('button', { name: 'Crear gasto', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('Revisa el importe')
  await page.unroute('**/api/groups/*/expenses')
  await dialog.getByRole('button', { name: 'Crear gasto', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.route('**/api/groups/*/balances', route => route.abort())
  await page.getByRole('button', { name: 'Actualizar gastos y balances', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('conectar con Splitly')
  await page.unroute('**/api/groups/*/balances')
  await page.getByRole('button', { name: 'Reintentar gastos y balances', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Cena compartida', exact: true })).toBeVisible()
})
