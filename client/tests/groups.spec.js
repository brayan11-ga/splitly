import { test, expect } from '@playwright/test'
import { randomUUID } from 'node:crypto'

async function register(page) {
  await page.goto('/register')
  await page.getByLabel('Nombre completo', { exact: true }).fill('Persona Grupos')
  await page.getByLabel('Correo electrónico', { exact: true }).fill(`${randomUUID()}@example.com`)
  await page.getByLabel('Contraseña', { exact: true }).fill('Una frase de prueba segura 123')
  await page.getByLabel('Confirmar contraseña', { exact: true }).fill('Una frase de prueba segura 123')
  await page.getByRole('button', { name: 'Crear mi cuenta', exact: true }).click()
  await expect(page).toHaveURL(/\/dashboard$/)
}
async function createGroup(page, name = 'Viaje a Cartagena') {
  await page.getByRole('button', { name: 'Crear grupo', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Crear grupo', exact: true })
  await dialog.getByLabel('Nombre del grupo').fill(name)
  await dialog.getByRole('button', { name: 'Crear grupo', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
}
async function addMember(page, name = 'Ana') {
  await page.getByRole('button', { name: 'Añadir participante' }).click()
  const dialog = page.getByRole('dialog', { name: 'Crear participante', exact: true })
  await dialog.getByLabel('Nombre del participante').fill(name)
  await dialog.getByRole('button', { name: 'Crear participante', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
}

test('CRUD real desde dashboard, búsqueda, detalle y participantes', async ({ page }) => {
  await register(page)
  await createGroup(page)
  await page.getByRole('link', { name: 'Ver todos mis grupos' }).click()
  await expect(page).toHaveURL(/\/groups$/)
  await page.getByRole('searchbox', { name: 'Buscar por nombre' }).fill('no existe')
  await expect(page.getByText('No encontramos grupos con ese nombre.')).toBeVisible()
  await page.getByRole('button', { name: 'Limpiar búsqueda' }).click()
  await page.getByRole('button', { name: 'Editar grupo Viaje a Cartagena', exact: true }).click()
  const edit = page.getByRole('dialog', { name: 'Editar grupo' })
  await edit.getByLabel('Nombre del grupo').fill('Casa Bogotá')
  await edit.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(edit).not.toBeVisible()
  await page.getByRole('searchbox', { name: 'Buscar por nombre' }).fill('bogota')
  await expect(page.getByRole('heading', { name: 'Casa Bogotá' })).toBeVisible()
  await page.getByRole('link', { name: 'Ver grupo Casa Bogotá' }).click()
  await expect(page).toHaveURL(/\/groups\/[a-f0-9-]+$/)
  await addMember(page)
  await page.getByRole('button', { name: 'Editar participante Ana', exact: true }).click()
  const memberEdit = page.getByRole('dialog', { name: 'Editar participante' })
  await memberEdit.getByLabel('Nombre del participante').fill('Andrea')
  await memberEdit.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(memberEdit).not.toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Casa Bogotá', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Andrea', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Eliminar participante Andrea', exact: true }).click()
  const memberDelete = page.getByRole('dialog', { name: 'Eliminar participante' })
  await memberDelete.getByRole('button', { name: 'Cancelar' }).click()
  await expect(page.getByRole('heading', { name: 'Andrea', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Eliminar participante Andrea', exact: true }).click()
  await memberDelete.getByRole('button', { name: 'Eliminar participante', exact: true }).click()
  await expect(memberDelete).not.toBeVisible()
  await expect(page.getByRole('heading', { name: 'Todo plan empieza por su gente.' })).toBeVisible()
  await page.getByRole('button', { name: 'Editar grupo', exact: true }).click()
  const detailEdit = page.getByRole('dialog', { name: 'Editar grupo' })
  await detailEdit.getByLabel('Nombre del grupo').fill('Plan final')
  await detailEdit.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(detailEdit).not.toBeVisible()
  await page.getByRole('button', { name: 'Eliminar grupo', exact: true }).click()
  const deleteGroup = page.getByRole('dialog', { name: 'Eliminar grupo', exact: true })
  await deleteGroup.getByRole('button', { name: 'Eliminar grupo', exact: true }).click()
  await expect(page).toHaveURL(/\/groups$/)
  await expect(page.getByRole('heading', { name: 'El próximo plan empieza aquí.' })).toBeVisible()
  await page.getByRole('link', { name: '↗ Dashboard', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'El próximo plan empieza aquí.' })).toBeVisible()
})

