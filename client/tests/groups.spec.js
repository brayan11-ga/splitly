test('validación local, Escape, foco y errores reales 403/422 recuperables', async ({ page }) => {
  await register(page)
  const trigger = page.getByRole('button', { name: 'Crear grupo', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('Nombre del grupo')).toBeFocused()
  await dialog.getByLabel('Nombre del grupo').fill('   ')
  await dialog.getByRole('button', { name: 'Crear grupo', exact: true }).click()
  await expect(dialog.getByText('Escribe un nombre. No puede contener solo espacios.')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await dialog.getByLabel('Nombre del grupo').fill('Plan')
  await page.route('**/api/groups', route => route.request().method() === 'POST'
    ? route.continue({ headers: { ...route.request().headers(), 'x-csrf-token': 'invalid' } }) : route.continue())
  await dialog.getByRole('button', { name: 'Crear grupo', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('No pudimos validar esta solicitud.')
  await page.unroute('**/api/groups')
  await page.route('**/api/groups', route => route.request().method() === 'POST'
    ? route.continue({ postData: JSON.stringify({ name: '' }) }) : route.continue())
  await dialog.getByRole('button', { name: 'Crear grupo', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('Escribe un nombre válido.')
  await page.unroute('**/api/groups')
  await dialog.getByRole('button', { name: 'Crear grupo', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('heading', { name: 'Plan', exact: true })).toBeVisible()
})

test('grupos ajenos y UUID inválidos no muestran controles de gestión', async ({ page, browser }) => {
  await register(page)
  await createGroup(page)
  await page.getByRole('link', { name: 'Ver grupo Viaje a Cartagena' }).click()
  const path = new URL(page.url()).pathname
  const otherContext = await browser.newContext({ baseURL: 'http://127.0.0.1:5175' })
  try {
    const other = await otherContext.newPage()
    await register(other)
    await other.goto(path)
    await expect(other.getByRole('alert')).toHaveText('Este grupo ya no está disponible o no tienes acceso a él.')
    await expect(other.getByRole('button', { name: 'Añadir participante' })).not.toBeVisible()
    await expect(other.getByRole('button', { name: 'Editar grupo', exact: true })).not.toBeVisible()
    await other.goto('/groups/not-a-uuid')
    await expect(other.getByRole('alert')).toContainText('El identificador del grupo no es válido.')
  } finally { await otherContext.close() }
})

test('sesión revocada redirige a login y muestra una explicación', async ({ page }) => {
  await register(page)
  const identity = await (await page.request.get('http://127.0.0.1:8001/api/auth/me')).json()
  await page.request.post('http://127.0.0.1:8001/api/auth/logout', {
    headers: { Origin: 'http://127.0.0.1:5175', 'X-CSRF-Token': identity.csrf_token },
  })
  await page.getByRole('link', { name: 'Ver todos mis grupos' }).click()
  await expect(page).toHaveURL(/\/login$/)
  await expect(page.getByRole('status')).toContainText('Inicia sesión para acceder a tus grupos.')
})

test('error de carga recuperable, responsive y capturas con datos reales', async ({ page }, testInfo) => {
  await register(page)
  await page.route('**/api/groups', route => route.abort())
  await page.getByRole('link', { name: 'Ver todos mis grupos' }).click()
  await expect(page.getByRole('alert')).toContainText('No pudimos conectar con Splitly.')
  await page.unroute('**/api/groups')
  await page.getByRole('button', { name: 'Reintentar' }).click()
  await createGroup(page, 'Casa compartida en Bogotá')
  await createGroup(page, 'Próximo viaje')
  await page.screenshot({ path: testInfo.outputPath('groups-desktop.png'), fullPage: true })
  await page.getByRole('link', { name: 'Ver grupo Casa compartida en Bogotá' }).click()
  await addMember(page, 'Ana María')
  await addMember(page, 'Pedro')
  await page.screenshot({ path: testInfo.outputPath('group-detail-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: testInfo.outputPath('group-detail-mobile.png'), fullPage: true })
  await page.getByRole('button', { name: 'Añadir participante' }).click()
  await page.screenshot({ path: testInfo.outputPath('member-dialog-mobile.png'), fullPage: true })
  await page.keyboard.press('Escape')
})
